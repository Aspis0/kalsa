#!/usr/bin/env node
/**
 * Writes workers/download/guide.ts from the tester guide markdown.
 *
 *   node scripts/build-guide.mjs <ALPHA-TESTERS.md> [--check] [--out <guide.ts>]
 *
 * The Italian guide is read from the sibling <ALPHA-TESTERS.it.md>.
 *
 * --check exits 1 when the committed guide.ts is not what the markdown produces.
 * --out writes or checks another module instead of the committed one.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parseBlocks, renderBlock } from "./markdown-subset.mjs";

const DEFAULT_OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../guide.ts");

// The page links #mac and #windows, so those two install sections keep their names.
const SECTION_IDS = {
  1: "requirements",
  2: "mac",
  3: "windows",
  4: "first-start",
  5: "phone",
  6: "problems",
  8: "uninstall",
};
// Section 7 is the download page itself, so the guide does not repeat it.
const DROPPED = new Set([7]);

function sectionNumber(text) {
  const match = /^(\d+)\. /.exec(text);
  return match ? Number(match[1]) : null;
}

// Bold is not counted: the Italian repeats one label where the English names two.
const PARITY_KEYS = ["paragraphs", "items", "quotes", "codeSpans"];

function sectionShapes(source) {
  const shapes = new Map();
  let shape = null;
  for (const block of parseBlocks(source)) {
    if (block.type === "h2") {
      const number = sectionNumber(block.text);
      if (number === null) throw new Error(`unnumbered section: ${block.text}`);
      shape = { paragraphs: 0, items: 0, quotes: 0, codeSpans: 0 };
      shapes.set(number, shape);
      continue;
    }
    if (shape === null) continue;
    if (block.type === "p") shape.paragraphs += 1;
    else if (block.type === "quote") shape.quotes += 1;
    else if (block.type === "ul" || block.type === "ol") shape.items += block.items.length;
    else continue;
    for (const text of block.items ?? [block.text]) {
      shape.codeSpans += (text.match(/`[^`]*`/g) ?? []).length;
    }
  }
  return shapes;
}

function describeShape(shape) {
  return `${shape.paragraphs} paragraphs, ${shape.items} list items, ${shape.quotes} quotes, ${shape.codeSpans} code spans`;
}

function assertParity(english, italian) {
  const en = sectionShapes(english);
  const it = sectionShapes(italian);
  for (const [number, want] of en) {
    const got = it.get(number);
    if (got === undefined) throw new Error(`section ${number} is missing from the Italian guide`);
    if (PARITY_KEYS.some((key) => want[key] !== got[key])) {
      throw new Error(
        `section ${number} differs: English has ${describeShape(want)}; Italian has ${describeShape(got)}`,
      );
    }
  }
  for (const number of it.keys()) {
    if (!en.has(number)) throw new Error(`section ${number} is missing from the English guide`);
  }
}

function guideLines(source) {
  const lines = [];
  const seen = new Set();
  let dropping = false;
  for (const block of parseBlocks(source)) {
    if (block.type === "h1") continue;
    if (block.type === "h2") {
      const number = sectionNumber(block.text);
      if (number === null) throw new Error(`unnumbered section: ${block.text}`);
      dropping = DROPPED.has(number);
      if (dropping) continue;
      if (!(number in SECTION_IDS)) throw new Error(`no anchor for section ${number}`);
      seen.add(number);
      lines.push(renderBlock(block, SECTION_IDS[number]));
      continue;
    }
    if (!dropping) lines.push(renderBlock(block));
  }
  for (const number of Object.keys(SECTION_IDS)) {
    if (!seen.has(Number(number))) throw new Error(`section ${number} missing from the markdown`);
  }
  return lines;
}

function guideConstant(name, source) {
  const body = guideLines(source).map((line) => `  ${JSON.stringify(line)},`).join("\n");
  return [`export const ${name} = [`, body, '].join("\\n");'].join("\n");
}

function guideModule(english, italian) {
  return [
    "// Generated by scripts/build-guide.mjs from the tester guide markdown. Do not edit.",
    guideConstant("GUIDE_HTML", english),
    "",
    guideConstant("GUIDE_HTML_IT", italian),
    "",
  ].join("\n");
}

const args = process.argv.slice(2);
const check = args.includes("--check");
const outAt = args.indexOf("--out");
const out = outAt === -1 ? DEFAULT_OUT : path.resolve(args[outAt + 1]);
const [source] = (outAt === -1 ? args : args.toSpliced(outAt, 2)).filter((arg) => arg !== "--check");
if (!source) {
  console.error("usage: build-guide.mjs <ALPHA-TESTERS.md> [--check] [--out <guide.ts>]");
  process.exit(2);
}

if (!source.endsWith(".md")) {
  console.error(`expected a .md path, got ${source}`);
  process.exit(2);
}
const italianSource = source.replace(/\.md$/, ".it.md");
const english = readFileSync(source, "utf8");
const italian = readFileSync(italianSource, "utf8");
assertParity(english, italian);
const expected = guideModule(english, italian);
if (check) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== expected) {
    console.error(`guide.ts is out of date with ${source}; run scripts/build-guide.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(out, expected);
}
